// 棋盘几何（仅用于前端渲染，与服务器逻辑无关）
// 坐标采用 15x15 网格，单位格。每个格用 [col, row] 表示。
export const COLORS = ['red', 'yellow', 'blue', 'green'];
export const CELL = 40; // 每格像素
export const N = 15; // 棋盘 15x15

// 四种颜色在主轨道上的起飞格编号（与服务器 board.js 保持一致）
export const START_INDEX = { red: 0, yellow: 26, blue: 39, green: 13 };

// 主轨道 52 格（顺时针，标准飞行棋十字布局）
export const MAIN = [
  [6, 13], [6, 12], [6, 11], [6, 10], [6, 9],
  [5, 8], [4, 8], [3, 8], [2, 8], [1, 8], [0, 8],
  [0, 7],
  [0, 6], [1, 6], [2, 6], [3, 6], [4, 6], [5, 6],
  [6, 5], [6, 4], [6, 3], [6, 2], [6, 1], [6, 0],
  [7, 0],
  [8, 0], [8, 1], [8, 2], [8, 3], [8, 4], [8, 5],
  [9, 6], [10, 6], [11, 6], [12, 6], [13, 6], [14, 6],
  [14, 7],
  [14, 8], [13, 8], [12, 8], [11, 8], [10, 8], [9, 8],
  [8, 9], [8, 10], [8, 11], [8, 12], [8, 13], [8, 14],
  [7, 14],
  [6, 14],
];

// 每条颜色的回家通道（4 格，从主轨道末端通往中心）
export const HOME = {
  red: [[7, 13], [7, 12], [7, 11], [7, 10]],
  yellow: [[7, 1], [7, 2], [7, 3], [7, 4]],
  blue: [[13, 7], [12, 7], [11, 7], [10, 7]],
  green: [[1, 7], [2, 7], [3, 7], [4, 7]],
};

// 每条颜色的基地（停机坪，4 架飞机初始位置）
export const BASE = {
  red: [[1, 13], [3, 13], [1, 11], [3, 11]],
  yellow: [[13, 1], [11, 1], [13, 3], [11, 3]],
  blue: [[13, 13], [11, 13], [13, 11], [11, 11]],
  green: [[1, 1], [3, 1], [1, 3], [3, 3]],
};

export const CENTER = [7, 7];

// 把飞机的 step 转成网格坐标 [col,row]
//   step<0    -> 基地（由调用方用 BASE 处理）
//   step 0..50 -> 主轨道
//   step 51..54 -> 回家通道
//   step 55   -> 中心
export function stepToCell(color, step) {
  if (step < 0) return null;
  if (step <= 50) return MAIN[(START_INDEX[color] + step) % 52];
  if (step <= 54) return HOME[color][step - 51];
  return CENTER;
}
